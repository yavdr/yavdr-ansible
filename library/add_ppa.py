from typing import Any
from ansible.module_utils.basic import AnsibleModule
import os
import json
import urllib.request
import tempfile
import shutil
import stat

LAUNCHPAD_API = "https://api.launchpad.net/1.0/~{owner}/+archive/ubuntu/{repo}"


def http_get(url: str, module: AnsibleModule):
    try:
        with urllib.request.urlopen(url, timeout=30) as r:
            return r.read().decode("utf-8")
    except Exception as e:
        module.fail_json(msg=f"Failed HTTP GET {url}: {e}")


def get_ppa_info(owner, repo, module: AnsibleModule):
    url = LAUNCHPAD_API.format(owner=owner, repo=repo)
    text = http_get(url, module)
    try:
        data = json.loads(text)
    except Exception as e:
        module.fail_json(msg=f"Invalid JSON from Launchpad API: {e}")
    # Launchpad provides signing_key_fingerprint field
    fp = data.get("signing_key_fingerprint")
    if not fp:
        module.fail_json(msg="Launchpad API did not return signing_key_fingerprint")
    return fp


def run_gpg_recv_and_export(fingerprint: str, module: AnsibleModule):
    """
    Create a temporary GNUPGHOME, receive key from keyserver.ubuntu.com,
    export ASCII-armored and binary forms, return (armor_str, binary_bytes).
    """
    tmpdir = tempfile.mkdtemp(prefix="gnupg-")
    # ensure correct permissions (700)
    os.chmod(tmpdir, 0o700)
    old = os.environ.get("GNUPGHOME")
    os.environ["GNUPGHOME"] = tmpdir

    rc: int
    bin_out: str
    err: str

    try:
        # receive key
        cmd_recv = [
            "gpg",
            "--batch",
            "--keyserver",
            "keyserver.ubuntu.com",
            "--recv-keys",
            fingerprint,
        ]
        rc, out, err = module.run_command(cmd_recv)
        if rc != 0:
            # try hkps as fallback
            cmd_recv = [
                "gpg",
                "--batch",
                "--keyserver",
                "hkps://keys.openpgp.org",
                "--recv-keys",
                fingerprint,
            ]
            rc2, out2, err2 = module.run_command(cmd_recv)
            if rc2 != 0:
                # combine errors and fail
                module.fail_json(
                    msg=f"gpg --recv-keys failed: {err}\nFallback failed: {err2}"
                )
        # export ASCII-armored
        cmd_export_armor = ["gpg", "--armor", "--export", fingerprint]
        rc, armor, err = module.run_command(cmd_export_armor)
        if rc != 0:
            module.fail_json(msg=f"gpg --armor --export failed: {err}")
        # export binary
        cmd_export_bin = ["gpg", "--export", fingerprint]

        rc, bin_out, err = module.run_command(cmd_export_bin)
        if rc != 0:
            module.fail_json(msg=f"gpg --export (binary) failed: {err}")
        # bin_out is bytes-like string (text). We want bytes.
        try:
            bin_bytes = bin_out.encode("latin-1")
        except Exception:
            # fallback
            bin_bytes = bin_out.encode("utf-8", errors="ignore")
        return armor, bin_bytes
    finally:
        # cleanup temp GNUPGHOME and restore old env
        if old is None:
            os.environ.pop("GNUPGHOME", None)
        else:
            os.environ["GNUPGHOME"] = old
        shutil.rmtree(tmpdir, ignore_errors=True)


def write_if_different(path, data_bytes, mode=0o644):
    """
    Write data_bytes to path only if different. Returns True if written.
    """
    if os.path.exists(path):
        try:
            with open(path, "rb") as f:
                existing = f.read()
            if existing == data_bytes:
                return False
        except Exception:
            # if reading fails, proceed to write
            pass
    # write atomically to temp file then rename
    d = os.path.dirname(path)
    os.makedirs(d, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=d)
    try:
        with os.fdopen(fd, "wb") as f:
            f.write(data_bytes)
        os.chmod(tmp, mode)
        os.replace(tmp, path)
    finally:
        if os.path.exists(tmp):
            try:
                os.remove(tmp)
            except Exception:
                pass
    return True


def build_sources_content(
    uri: str,
    codename: str,
    components: list[str] | tuple[str, ...] | Any,
    signed_by_value: str | bytes | None,
    deb_src: bool = False,
):
    """
    Build .sources content as per Ubuntu 26.04 style.
    signed_by_value is either a file path or an ASCII-armored block (string).
    For inline armor, we put Signed-By: <armor> (same line, Option A).
    """
    types = "deb"
    if deb_src:
        types = "deb deb-src"
    # Components may be list or string
    if isinstance(components, (list, tuple)):
        comps = " ".join([str(c) for c in components])
    else:
        comps = str(components)

    lines: list[str] = []
    lines.append(f"Types: {types}")
    lines.append(f"URIs: {uri}")
    lines.append(f"Suites: {codename}")
    lines.append(f"Components: {comps}")

    # signed_by_value may be binary path or armor string
    if signed_by_value is None:
        lines.append("Signed-By:")
    else:
        # If signed_by_value looks like a path (no '-----BEGIN'), treat as file path
        if isinstance(signed_by_value, bytes):
            # shouldn't happen here
            signed_by_line = f"Signed-By: {signed_by_value.decode('utf-8')}"
            lines.append(signed_by_line)
        else:
            sval = str(signed_by_value)
            if "-----BEGIN PGP" in sval:
                # Option A: Signed-By: -----BEGIN PGP PUBLIC KEY BLOCK-----
                # Put the armor immediately after the colon+space, preserving newlines inside the armor.
                # Ensure armor has no leading/trailing spaces (but keep newlines).
                armor = sval.strip("\n")
                # Prepend a single space so line begins: Signed-By: -----BEGIN...
                armor_lines = armor.splitlines()
                first_line = f"Signed-By: {armor_lines[0]}"
                lines.append(first_line)
                # make sure the format matches the requirements - we need to indent the following lines by one space
                lines.append(
                    " ."
                )  # this is used instead of the second line of the armor_lines
                # append the rest of armor lines as-is (starting from third line)
                for line in armor_lines[2:]:
                    lines.append(f" {line}")
            else:
                # treat as path
                lines.append(f"Signed-By: {sval}")

    # join with newline and ensure trailing newline
    content = "\n".join(lines) + "\n"
    return content.encode("utf-8")


def main():
    module: AnsibleModule = AnsibleModule(
        argument_spec=dict(
            repo=dict(type="str", required=True),
            state=dict(type="str", choices=["present", "absent"], default="present"),
            inline_key=dict(type="bool", default=False),
            deb_src=dict(type="bool", default=False),
            components=dict(required=False, default="main"),
            codename=dict(required=False, type="str"),
        ),
        supports_check_mode=False,
    )

    repo = module.params["repo"]
    state = module.params["state"]
    inline_key = module.params["inline_key"]
    deb_src = module.params["deb_src"]
    components = module.params["components"]
    codename = module.params["codename"]

    if not repo.startswith("ppa:"):
        module.fail_json(msg="repo must start with 'ppa:' (e.g. 'ppa:deadsnakes/ppa')")

    # parse owner and repo_name
    try:
        owner_repo = repo[4:]
        owner, repo_name = owner_repo.split("/", 1)
    except Exception:
        module.fail_json(msg="repo must be in format 'ppa:owner/name'")

    # detect codename if not provided
    if not codename:
        rc, out, err = module.run_command(["lsb_release", "-sc"])
        if rc != 0:
            module.fail_json(msg=f"Failed to detect distribution codename: {err}")
        codename = out.strip()

    # create target .sources path
    sources_name = f"{owner}-ubuntu-{repo_name.replace('.', '_')}-{codename}.sources"
    sources_path = os.path.join("/etc/apt/sources.list.d", sources_name)

    # base URI used by Ubuntu for PPAs
    uri = f"https://ppa.launchpadcontent.net/{owner}/{repo_name}/ubuntu/"

    keyring_path = f"/usr/share/keyrings/{owner}-{repo_name}.gpg"

    if state == "absent":
        changed = False
        # remove .sources file
        if os.path.exists(sources_path):
            try:
                os.remove(sources_path)
                changed = True
            except Exception as e:
                module.fail_json(msg=f"Failed to remove {sources_path}: {e}")
        # remove keyring file if exists (only for non-inline)
        if os.path.exists(keyring_path):
            try:
                os.remove(keyring_path)
                changed = True
            except Exception as e:
                module.fail_json(msg=f"Failed to remove {keyring_path}: {e}")
        module.exit_json(changed=changed, msg="PPA removed (if present).")

    # state == present
    # Get fingerprint
    fingerprint = get_ppa_info(owner, repo_name, module)

    # Fetch key (armor + binary) using isolated GNUPGHOME
    armor, bin_bytes = run_gpg_recv_and_export(fingerprint, module)

    changed = False
    keyring_written_path = None

    if inline_key:
        # embed armor inline
        # armor is ASCII-armored string like "-----BEGIN PGP PUBLIC KEY BLOCK-----\n...\n"
        # We'll pass it into build_sources_content which will format Signed-By: <armor...>
        signed_by_value = armor
    else:
        # write binary key to /usr/share/keyrings/<owner>-<repo>.gpg
        try:
            written = write_if_different(keyring_path, bin_bytes, mode=0o644)
        except Exception as e:
            module.fail_json(msg=f"Failed to write keyring {keyring_path}: {e}")
        if written:
            changed = True
        keyring_written_path = keyring_path
        signed_by_value = keyring_path

    # build content and write .sources file if different
    content_bytes = build_sources_content(
        uri, codename, components, signed_by_value, deb_src=deb_src
    )
    try:
        wrote = write_if_different(sources_path, content_bytes, mode=0o644)
    except Exception as e:
        module.fail_json(msg=f"Failed to write {sources_path}: {e}")
    if wrote:
        changed = True

    result = dict(
        changed=changed,
        msg=f"PPA present: {repo}",
        fingerprint=fingerprint,
        path=sources_path,
    )
    if keyring_written_path:
        result["keyring"] = keyring_written_path

    module.exit_json(**result)


if __name__ == "__main__":
    main()
